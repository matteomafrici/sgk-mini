#!/usr/bin/env python3
"""Annulus case model, OpenFOAM case generation and dataset record assembly.

The annular case is an instance of the pipeline, not its definition. Everything
specific to it (the analytical model, the 2 degree wedge, the dictionary
literals) lives in this file; the sampling and orchestration do not need to know
about it.

The OpenFOAM case is generated by copying the validated reference dictionaries
and replacing only the literal values that belong to the case. That keeps the
solver configuration identical across the dataset and makes every changed number
visible in one function.
"""

import hashlib
import json
import math
import os
import platform
import re
import shutil
import subprocess
import sys
import time

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REFERENCE_CASE = os.path.join(REPO, "validation", "openfoam", "annulus_cyclic")
DLL = os.path.join(REPO, "src", "SGK.Geometry", "bin", "Debug", "net9.0", "SGK.Geometry.dll")
DATASET_ROOT = os.path.expanduser("~/data/datasets/sgk-mini")

SCHEMA = "sgk-mini.dataset-record.v1"

# The fluid is fixed for this family; it is part of the case request so a later
# family can change it without changing the pipeline.
RHO = 1000.0
MU = 1.0e-3


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def _canonical(values):
    return json.dumps(values, sort_keys=True, separators=(",", ":"))


class Request:
    """One requested annular case.

    Units are explicit in the names. The case id is a deterministic hash of the
    requested parameters, so the same request always lands in the same directory
    and a changed request never overwrites a previous case.
    """

    def __init__(self, outer_radius_mm, gap_mm, length_mm, flow_rate_m3_s,
                 voxel_size_mm=0.2, density_kg_m3=RHO, viscosity_pa_s=MU):
        self.outer_radius_mm = float(outer_radius_mm)
        self.gap_mm = float(gap_mm)
        self.length_mm = float(length_mm)
        self.flow_rate_m3_s = float(flow_rate_m3_s)
        self.voxel_size_mm = float(voxel_size_mm)
        self.density_kg_m3 = float(density_kg_m3)
        self.viscosity_pa_s = float(viscosity_pa_s)

    @property
    def inner_radius_mm(self):
        return self.outer_radius_mm - self.gap_mm

    @property
    def mean_velocity_m_s(self):
        area = math.pi * (self.outer_radius_mm ** 2 - self.inner_radius_mm ** 2) * 1.0e-6
        return self.flow_rate_m3_s / area

    @property
    def hydraulic_diameter_m(self):
        return 2.0 * self.gap_mm * 1.0e-3

    @property
    def reynolds(self):
        return (self.density_kg_m3 * self.mean_velocity_m_s
                * self.hydraulic_diameter_m / self.viscosity_pa_s)

    @property
    def case_id(self):
        payload = {
            "outer_radius_mm": f"{self.outer_radius_mm:.12g}",
            "gap_mm": f"{self.gap_mm:.12g}",
            "length_mm": f"{self.length_mm:.12g}",
            "flow_rate_m3_s": f"{self.flow_rate_m3_s:.12g}",
            "voxel_size_mm": f"{self.voxel_size_mm:.12g}",
            "density_kg_m3": f"{self.density_kg_m3:.12g}",
            "viscosity_pa_s": f"{self.viscosity_pa_s:.12g}",
        }
        return "ann-" + hashlib.sha256(_canonical(payload).encode()).hexdigest()[:8]

    def as_dict(self):
        return {
            "case_id": self.case_id,
            "outer_radius_mm": self.outer_radius_mm,
            "inner_radius_mm": self.inner_radius_mm,
            "gap_mm": self.gap_mm,
            "length_mm": self.length_mm,
            "flow_rate_m3_s": self.flow_rate_m3_s,
            "voxel_size_mm": self.voxel_size_mm,
            "density_kg_m3": self.density_kg_m3,
            "viscosity_pa_s": self.viscosity_pa_s,
            "mean_velocity_m_s": self.mean_velocity_m_s,
            "reynolds": self.reynolds,
        }

    @classmethod
    def from_dict(cls, values):
        return cls(
            values["outer_radius_mm"],
            values["gap_mm"],
            values["length_mm"],
            values["flow_rate_m3_s"],
            values.get("voxel_size_mm", 0.2),
            values.get("density_kg_m3", RHO),
            values.get("viscosity_pa_s", MU),
        )


def admissibility(request, min_radius_voxels=3.0):
    """Reasons a request cannot be an honest case, in priority order.

    `gap >= 3 voxels` is the task's lower bound. The same feature rule is
    applied to the inner radius: a 0.2 mm radius is one voxel at the default
    resolution, and its reconstruction is not a measurement of the requested
    geometry.
    """
    problems = []

    if request.inner_radius_mm <= 0.0:
        problems.append("inner radius is not positive")
    if request.gap_mm < 3.0 * request.voxel_size_mm - 1.0e-12:
        problems.append(
            f"gap {request.gap_mm:.4f} mm is below 3 voxels "
            f"({3.0 * request.voxel_size_mm:.4f} mm)"
        )
    if request.inner_radius_mm < min_radius_voxels * request.voxel_size_mm - 1.0e-12:
        problems.append(
            f"inner radius {request.inner_radius_mm:.4f} mm is below "
            f"{min_radius_voxels:g} voxels ({min_radius_voxels * request.voxel_size_mm:.4f} mm)"
        )
    if request.reynolds >= 2000.0:
        problems.append(f"Reynolds number {request.reynolds:.1f} is not laminar")
    if request.length_mm <= 0.0:
        problems.append("length is not positive")

    return problems


def geometry_config(request, output_dir):
    return {
        "CaseId": request.case_id,
        "OuterRadiusMm": request.outer_radius_mm,
        "InnerRadiusMm": request.inner_radius_mm,
        "LengthMm": request.length_mm,
        "VoxelSizeMm": request.voxel_size_mm,
        "DensityKgPerM3": request.density_kg_m3,
        "DynamicViscosityPaS": request.viscosity_pa_s,
        "VolumetricFlowRateM3PerS": request.flow_rate_m3_s,
        "OutputDirectory": output_dir,
    }


def run_geometry(request, case_dir):
    geometry_dir = os.path.join(case_dir, "geometry")
    os.makedirs(geometry_dir, exist_ok=True)

    config_path = os.path.join(case_dir, "geometry-config.json")
    with open(config_path, "w") as f:
        json.dump(geometry_config(request, geometry_dir), f, indent=2)

    result = subprocess.run(
        ["dotnet", DLL, "--auto-exit", "--config", config_path],
        cwd=os.path.dirname(DLL),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )

    log_path = os.path.join(case_dir, "log.geometry")
    with open(log_path, "w") as f:
        f.write(result.stdout)
        f.write(result.stderr)

    if result.returncode != 0:
        raise RuntimeError(
            f"geometry stage failed ({result.returncode}); see {log_path}")

    features_path = os.path.join(geometry_dir, f"{request.case_id}.features.json")
    physical_path = os.path.join(geometry_dir, f"{request.case_id}.physical-case.json")
    vdb_path = os.path.join(geometry_dir, f"{request.case_id}.vdb")

    for path in (features_path, physical_path, vdb_path):
        if not os.path.isfile(path) or os.path.getsize(path) == 0:
            raise RuntimeError(f"geometry stage did not produce {path}")

    with open(features_path) as f:
        features = json.load(f)
    with open(physical_path) as f:
        physical = json.load(f)

    return features, physical, features_path, physical_path, vdb_path


def geometry_checks(request, features, physical):
    checks = []

    def add(name, passed, detail):
        checks.append({"name": name, "passed": bool(passed), "detail": detail})

    add("case identity (features)", features.get("CaseId") == request.case_id,
        f"{features.get('CaseId')} vs {request.case_id}")
    add("case identity (physical)", physical.get("CaseId") == request.case_id,
        f"{physical.get('CaseId')} vs {request.case_id}")

    ri_err_um = abs(physical["InnerRadiusMm"] - request.inner_radius_mm) * 1.0e3
    ro_err_um = abs(physical["OuterRadiusMm"] - request.outer_radius_mm) * 1.0e3
    l_err_um = abs(physical["LengthMm"] - request.length_mm) * 1.0e3

    add("inner radius within 10 um", ri_err_um <= 10.0, f"{ri_err_um:.4f} um")
    add("outer radius within 10 um", ro_err_um <= 10.0, f"{ro_err_um:.4f} um")
    add("length within 10 um", l_err_um <= 10.0, f"{l_err_um:.4f} um")

    nominal_volume = (math.pi
                      * (request.outer_radius_mm ** 2 - request.inner_radius_mm ** 2)
                      * request.length_mm)
    volume_error = 100.0 * (features["VolumeMm3"] - nominal_volume) / nominal_volume
    add("volume error below 0.1 %", abs(volume_error) < 0.1, f"{volume_error:+.4f} %")

    add("voxel size matches the request",
        abs(features.get("VoxelSizeMm", -1) - request.voxel_size_mm) < 1.0e-12,
        f"{features.get('VoxelSizeMm')} vs {request.voxel_size_mm}")

    q_rel = abs(physical["VolumetricFlowRateM3PerS"] - request.flow_rate_m3_s) / request.flow_rate_m3_s
    add("record flow rate matches the request", q_rel < 1.0e-9, f"relative {q_rel:.2e}")

    add("record is laminar", physical["ReynoldsNumber"] < 2000.0,
        f"Re={physical['ReynoldsNumber']:.2f}")

    return checks


def _replace_literal(text, name, value, pattern=None):
    """Replace exactly one literal and fail if the expected form is absent."""
    pattern = pattern or rf"(?m)^{name}\s+[^;\n]+;"
    replacement = f"{name} {value};"
    new_text, count = re.subn(pattern, replacement, text)
    if count != 1:
        raise RuntimeError(f"expected exactly one '{name}' literal, found {count}")
    return new_text


def prepare_openfoam_case(request, physical, case_dir):
    """Copy the validated reference dictionaries and set the case literals.

    No other change is made: the mesh topology, schemes, relaxation and
    boundary condition types are the ones the reference validation certified.
    """
    case_out = os.path.join(case_dir, "openfoam")
    if os.path.isdir(case_out):
        shutil.rmtree(case_out)

    for sub in ("system", "constant", "0"):
        shutil.copytree(
            os.path.join(REFERENCE_CASE, sub),
            os.path.join(case_out, sub),
            ignore=shutil.ignore_patterns("polyMesh"),
        )

    block_mesh = os.path.join(case_out, "system", "blockMeshDict")
    with open(block_mesh) as f:
        text = f.read()

    # Keep the radial cell size near 20 um, the size the reference case was
    # validated with, instead of using 100 cells for every gap. A 0.6 mm gap
    # with 100 cells gives 6 um cells and an aspect ratio that checkMesh flags
    # as under-determined; 30 cells keep the same absolute resolution without
    # pretending the extra cells add information.
    n_radial = int(round(request.gap_mm / 0.020))
    n_radial = min(100, max(20, n_radial))
    if n_radial % 2:
        n_radial += 1
    n_half = n_radial // 2

    text = _replace_literal(text, "nR1", str(n_half))
    text = _replace_literal(text, "nR2", str(n_half))
    text = _replace_literal(text, "Ri", f"{physical['InnerRadiusMm'] * 1e-3:.17g}")
    text = _replace_literal(text, "Ro", f"{physical['OuterRadiusMm'] * 1e-3:.17g}")
    text = _replace_literal(text, "L", f"{physical['LengthMm'] * 1e-3:.17g}")
    with open(block_mesh, "w") as f:
        f.write(text)

    fv_options = os.path.join(case_out, "constant", "fvOptions")
    with open(fv_options) as f:
        text = f.read()
    text = _replace_literal(
        text, "Ubar", f"({physical['MeanVelocityMPerS']:.17g} 0 0)",
        pattern=r"(?m)^\s*Ubar\s+\([^)]*\);")
    with open(fv_options, "w") as f:
        f.write(text)

    transport = os.path.join(case_out, "constant", "transportProperties")
    with open(transport) as f:
        text = f.read()
    nu = physical["DynamicViscosityPaS"] / physical["DensityKgPerM3"]
    text = _replace_literal(text, "nu", f"{nu:.17g}")
    with open(transport, "w") as f:
        f.write(text)

    with open(os.path.join(case_out, "case.json"), "w") as f:
        json.dump({"CaseId": request.case_id,
                   "Note": "Generated from the requested case; validated against the physical record before the solver runs."},
                  f, indent=2)

    return case_out


def run_reference(case_dir, physical_path):
    case_out = os.path.join(case_dir, "openfoam")
    env = dict(os.environ)
    env["CASE_DIR"] = case_out
    env["BENCHMARK"] = physical_path
    env["SKIP_FIGURES"] = "1"

    result = subprocess.run(
        ["bash", os.path.join(REPO, "validation", "run_annulus.sh"), "--check"],
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )

    log_path = os.path.join(case_dir, "log.reference")
    with open(log_path, "w") as f:
        f.write(result.stdout)

    validation_path = os.path.join(case_out, "validation.json")
    report = None
    if os.path.isfile(validation_path):
        with open(validation_path) as f:
            report = json.load(f)

    return result.returncode, report, log_path, validation_path


def mesh_check(case_dir):
    path = os.path.join(case_dir, "openfoam", "log.checkMesh")
    if not os.path.isfile(path):
        return False, "checkMesh log missing"
    with open(path) as f:
        text = f.read()
    if "Mesh OK." not in text:
        lines = [line for line in text.splitlines() if "Failed" in line or "***" in line]
        return False, "; ".join(lines[:5]) or "Mesh OK not reported"
    if "Failed" in text:
        return False, "checkMesh reported Failed"
    return True, "Mesh OK"


def _artifact_manifest(case_dir, exclude):
    manifest = {}
    for root, _, files in os.walk(case_dir):
        for name in sorted(files):
            path = os.path.join(root, name)
            rel = os.path.relpath(path, case_dir)
            if rel in exclude:
                continue
            manifest[rel] = sha256(path)
    return dict(sorted(manifest.items()))


def provenance():
    def command(*args):
        try:
            return subprocess.run(args, capture_output=True, text=True, timeout=30).stdout.strip()
        except Exception:
            return "unavailable"

    git_commit = command("git", "-C", REPO, "rev-parse", "HEAD")
    git_dirty = command("git", "-C", REPO, "status", "--porcelain")

    try:
        import numpy
        numpy_version = numpy.__version__
    except Exception:
        numpy_version = "unavailable"

    foam_version = command(
        "bash", "-c",
        "source ~/opt/OpenFOAM/OpenFOAM-v2606/etc/bashrc >/dev/null 2>&1; "
        "echo $WM_PROJECT_VERSION",
    )

    return {
        "timestamp_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "host": platform.node(),
        "platform": platform.platform(),
        "git_commit": git_commit,
        "git_dirty": bool(git_dirty),
        "dotnet_version": command("dotnet", "--version"),
        "openfoam_version": foam_version,
        "python_version": sys.version.split()[0],
        "numpy_version": numpy_version,
    }


def assemble(case_dir, request, features, physical, features_path, physical_path,
             vdb_path, geometry_checks_list, returncode, report, validation_path):
    ok = True
    reasons = []

    failed_geometry = [c for c in geometry_checks_list if not c["passed"]]
    if failed_geometry:
        ok = False
        reasons.append("geometry: " + "; ".join(c["name"] for c in failed_geometry))

    mesh_ok, mesh_detail = mesh_check(case_dir)
    if not mesh_ok:
        ok = False
        reasons.append(f"mesh: {mesh_detail}")

    if report is None:
        ok = False
        reasons.append("reference run produced no validation report")
        checks = []
    else:
        checks = report["checks"]
        failed_reference = [c for c in checks if not c["passed"]]
        if failed_reference:
            ok = False
            reasons.append("reference: " + "; ".join(c["name"] for c in failed_reference))
        if returncode != 0 and not failed_reference:
            ok = False
            reasons.append(f"reference script exited {returncode}")

    artifacts = _artifact_manifest(
        case_dir,
        exclude={"dataset-record.json"},
    )

    record = {
        "schema": SCHEMA,
        "case_id": request.case_id,
        "status": "ok" if ok else "failed",
        "failure_reason": None if ok else "; ".join(reasons),
        "request": request.as_dict(),
        "geometry": {
            "features": features,
            "physical": physical,
            "checks": geometry_checks_list,
            "vdb_sha256": sha256(vdb_path),
            "vdb_bytes": os.path.getsize(vdb_path),
        },
        "reference": {
            "solver_exit_code": returncode,
            "mesh": mesh_detail,
            "report": report["report"] if report else None,
            "checks": checks,
        },
        "artifacts": artifacts,
        "provenance": provenance(),
    }

    return record


def run_case(request, root=DATASET_ROOT):
    """Run one requested case end to end and return its dataset record.

    Every failure path still writes a record with the reason and whatever
    artifacts were produced. Nothing is deleted to make the dataset look clean.
    """
    case_dir = os.path.join(root, request.case_id)
    os.makedirs(case_dir, exist_ok=True)

    with open(os.path.join(case_dir, "case-request.json"), "w") as f:
        json.dump(request.as_dict(), f, indent=2)

    try:
        features, physical, features_path, physical_path, vdb_path = run_geometry(request, case_dir)
    except Exception as exc:
        record = {
            "schema": SCHEMA,
            "case_id": request.case_id,
            "status": "failed",
            "failure_reason": f"geometry: {exc}",
            "request": request.as_dict(),
            "geometry": None,
            "reference": None,
            "artifacts": _artifact_manifest(case_dir, exclude={"dataset-record.json"}),
            "provenance": provenance(),
        }
        with open(os.path.join(case_dir, "dataset-record.json"), "w") as f:
            json.dump(record, f, indent=2)
        return record

    geometry_checks_list = geometry_checks(request, features, physical)

    prepare_openfoam_case(request, physical, case_dir)

    # The preflight is run inside run_annulus.sh before blockMesh. If the
    # generated dictionaries and the record disagree, the solver never starts.
    returncode, report, _, validation_path = run_reference(case_dir, physical_path)

    record = assemble(
        case_dir, request, features, physical, features_path, physical_path,
        vdb_path, geometry_checks_list, returncode, report, validation_path,
    )

    with open(os.path.join(case_dir, "dataset-record.json"), "w") as f:
        json.dump(record, f, indent=2)

    with open(os.path.join(root, "index.json"), "w") as f:
        json.dump(index_entries(root), f, indent=2)

    return record


def index_entries(root):
    entries = []
    for name in sorted(os.listdir(root)):
        case_dir = os.path.join(root, name)
        record_path = os.path.join(case_dir, "dataset-record.json")
        if not os.path.isfile(record_path):
            continue
        with open(record_path) as f:
            record = json.load(f)
        reference = record.get("reference") or {}
        report = reference.get("report") or {}
        entries.append({
            "case_id": record["case_id"],
            "status": record["status"],
            "failure_reason": record.get("failure_reason"),
            "outer_radius_mm": record["request"]["outer_radius_mm"],
            "gap_mm": record["request"]["gap_mm"],
            "length_mm": record["request"]["length_mm"],
            "flow_rate_m3_s": record["request"]["flow_rate_m3_s"],
            "reynolds": record["request"]["reynolds"],
            "volume_error_pct": next(
                (c["detail"] for c in (record.get("geometry") or {}).get("checks", [])
                 if c["name"] == "volume error below 0.1 %"), None),
            "flow_error_pct": report.get("Q_err_pct"),
            "dpL_error_pct": report.get("dpL_err_pct"),
            "profile_mean_pct": (report.get("profile") or {}).get("mean_pct"),
            "profile_max_pct": (report.get("profile") or {}).get("max_pct"),
            "record": os.path.join(case_dir, "dataset-record.json"),
        })
    return entries
